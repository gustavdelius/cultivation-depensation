// Map the (F_forage, F_pred) plane with the validated engine:
//   * invasion boundary F_inv(F_forage): R0 of a rare predator in State C = 1
//   * collapse (fold) boundary F_crit(F_forage): largest F_pred at which the
//     coexistence branch, followed by continuation from State A, survives
//   * equilibrium biomass and yield on both branches, for the charts
// Writes interactive/regimes_data.js (window.REGIMES).
// Run from the project root:  node interactive/compute_regimes.js
"use strict";
const fs = require("fs");
const path = require("path");
const MODEL = require(path.join(__dirname, "model_data.js"));
const { createEngine } = require(path.join(__dirname, "engine.js"));

const DT = 0.2;
const eng = createEngine(MODEL);
const round = (x, d = 4) => Number(x.toFixed(d));

// Run to steady state. Returns "steady", "collapsed" or "timeout".
function settle(minYears = 60, maxYears = 3000) {
  let prev = [eng.biomass(0), eng.biomass(1)];
  for (let y = 1; y <= maxYears; y++) {
    for (let k = 0; k < 5; k++) eng.step(DT);
    if (y % 10 !== 0) continue;
    const cur = [eng.biomass(0), eng.biomass(1)];
    if (cur[1] < 0.05 && prev[1] < 0.05 * 1.5 && y >= minYears) {
      // Predator effectively gone and still falling: let the rest settle
      return "collapsed";
    }
    const change = Math.max(...cur.map((c, i) => Math.abs(c - prev[i]) / Math.max(c, 1)));
    if (y >= minYears && change < 1e-7) return "steady";
    prev = cur;
  }
  return "timeout";
}

function snapshotStats() {
  return {
    Bf: round(eng.biomass(0), 3), Bp: round(eng.biomass(1), 3),
    Yf: round(eng.yieldRate(0), 4), Yp: round(eng.yieldRate(1), 4),
  };
}

const Ff_grid = [];
for (let x = 0; x <= 0.6001; x += 0.025) Ff_grid.push(round(x, 3));
const Fp_step = 0.025;

// ---- Branch C (no predator) and invasion boundary ----------------------
const branchC = [];
eng.loadState("State_C");
for (const Ff of Ff_grid) {
  eng.state.effort.set([Ff, 0]);
  eng.remove(1);
  settle(100);
  const base = snapshotStats();
  const R0at = (Fp) => {
    eng.state.effort[1] = Fp;
    const r0 = eng.diagnostics().cohort[1].R0;
    eng.state.effort[1] = 0;
    return r0;
  };
  const R0_0 = R0at(0);
  let Finv = 0;
  if (R0_0 > 1) {
    let lo = 0, hi = 2;
    for (let it = 0; it < 50; it++) {
      const mid = 0.5 * (lo + hi);
      if (R0at(mid) > 1) lo = mid; else hi = mid;
    }
    Finv = 0.5 * (lo + hi);
  }
  branchC.push({ Ff, ...base, R0_pred: round(R0_0, 4), F_inv: round(Finv, 4) });
  console.log(`C  Ff=${Ff.toFixed(3)}  Bf=${base.Bf.toFixed(1)}  R0_pred=${R0_0.toFixed(3)}  F_inv=${Finv.toFixed(4)}`);
}

// ---- Branch A (coexistence) by continuation and collapse boundary -------
const branchA = [];       // rows: {Ff, Fp, Bf, Bp, Yf, Yp}
const fold = [];
eng.loadState("State_A");
let startOfRow = eng.snapshot();
for (const Ff of Ff_grid) {
  eng.restore(startOfRow);
  eng.state.effort.set([Ff, 0]);
  settle(100);
  startOfRow = eng.snapshot();
  let lastAlive = null, lastAliveFp = 0, firstDeadFp = null;
  for (let Fp = 0; Fp <= 0.8001; Fp += Fp_step) {
    eng.state.effort.set([Ff, Fp]);
    const status = settle(80);
    if (status === "collapsed" || eng.biomass(1) < 0.05) { firstDeadFp = Fp; break; }
    lastAlive = eng.snapshot();
    lastAliveFp = Fp;
    branchA.push({ Ff, Fp: round(Fp, 3), ...snapshotStats() });
  }
  // Bisect between the last surviving and first collapsing F_pred
  let lo = lastAliveFp, hi = firstDeadFp ?? 0.8, alive = lastAlive;
  for (let it = 0; it < 8; it++) {
    const mid = 0.5 * (lo + hi);
    eng.restore(alive);
    eng.state.effort.set([Ff, mid]);
    const status = settle(150, 4000);
    if (status !== "collapsed" && eng.biomass(1) >= 0.05) { lo = mid; alive = eng.snapshot(); }
    else hi = mid;
  }
  eng.restore(alive);
  const edge = snapshotStats();
  fold.push({ Ff, F_crit: round(0.5 * (lo + hi), 4), Bp_at_edge: edge.Bp, Bf_at_edge: edge.Bf });
  console.log(`A  Ff=${Ff.toFixed(3)}  F_crit=${(0.5 * (lo + hi)).toFixed(4)}  (Bp at edge ${edge.Bp.toFixed(1)})`);
}

const out = {
  generated: new Date().toISOString().slice(0, 10),
  dt: DT,
  Ff_grid, Fp_step,
  branchC, branchA, fold,
};
fs.writeFileSync(
  path.join(__dirname, "regimes_data.js"),
  "// Generated by interactive/compute_regimes.js. Do not edit by hand.\n" +
  "(function (root) { var REGIMES = " + JSON.stringify(out) +
  "; if (typeof module !== 'undefined') module.exports = REGIMES; else root.REGIMES = REGIMES; })(this);\n"
);
console.log("Wrote interactive/regimes_data.js");
